package com.fileapex.domain.clipboard

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * What the automatic clipboard sync must never send: a clip the OS or a password manager marked as sensitive, and a
 * short text that looks like a one-time code. A manual send by the user is not gated here. Each platform reads its own
 * marker names (Android `IS_SENSITIVE`, macOS pasteboard types, Windows clipboard formats, Linux selection targets) and
 * asks this one owner whether they mean "sensitive".
 */
object SensitiveClipPolicy {
    const val OTP_MAX_BYTES = 1024
    private const val OTP_MAX_CHARS = 200

    private val markers = setOf(
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
        "x-kde-passwordmanagerhint",
        "excludeclipboardcontentfrommonitorprocessing",
        "clipboard viewer ignore"
    )

    /** A bare six-digit number (or 3 and 3) is the usual one-time code; shorter or longer bare numbers are zip codes, prices and ids, so those need a code word. */
    private val bareCode = Regex("""^(\d{6}|\d{3}[ -]\d{3})$""")
    private val codeNamedBeforeDigits =
        Regex("""(?i)(?:code|otp|passcode|código|codigo|验证码|驗證碼)\s*(?:is|es|are|:|=|-|：)?\s*(?<![\d])(\d{4,8}|\d{3,4}[ -]\d{3,4})(?!\d)""")
    private val digitsBeforeIsYour = Regex("""(?i)(?<!\d)(?:\d{4,8}|\d{3,4}[ -]\d{3,4})\s+(?:is your|is the|es tu)\b""")

    fun hasSensitiveMarker(formatNames: Collection<String>): Boolean =
        formatNames.any { it.trim().lowercase() in markers }

    /** Windows `CanIncludeInClipboardHistory`: 0 keeps the clip out of history and cloud sync. */
    fun windowsHistoryExcluded(canIncludeInClipboardHistory: Int?): Boolean = canIncludeInClipboardHistory == 0

    fun looksLikeOneTimeCode(text: String): Boolean {
        if (text.length > OTP_MAX_CHARS || text.encodeToByteArray().size > OTP_MAX_BYTES) return false
        val trimmed = text.trim()
        if (trimmed.isEmpty()) return false
        return bareCode.matches(trimmed) || codeNamedBeforeDigits.containsMatchIn(trimmed) || digitsBeforeIsYour.containsMatchIn(trimmed)
    }

    /**
     * True when the automatic sync must not send [text]. [isMarked] is the platform's marker read: on macOS it waits for
     * AppKit's main thread, so it runs on the IO dispatcher and never on the caller, which can be the UI thread at window
     * focus and quit. A code-like text is decided without asking the platform.
     */
    suspend fun blocksAutomaticSend(text: String, isMarked: () -> Boolean): Boolean =
        looksLikeOneTimeCode(text) || withContext(Dispatchers.IO) { isMarked() }
}
